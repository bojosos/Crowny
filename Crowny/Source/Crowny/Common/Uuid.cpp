    const UUID UUID::EMPTY = { 0, 0, 0, 0 };

    UUID::UUID(uint32_t data1, uint32_t data2, uint32_t data3, uint32_t data4) : m_Data{ data1, data2, data3, data4 } {}

    UUID::UUID(const String& uuid)
    {
        m_Data[0] = m_Data[1] = m_Data[2] = m_Data[3] = 0;
        if (uuid.size() != 36)
            return;
        if (uuid[8] != '-' || uuid[13] != '-' || uuid[18] != '-' || uuid[23] != '-')
            return;

        auto parseHex = [&](uint32_t& out, uint32_t& idx, int32_t from, int32_t to) -> bool {
            for (int32_t i = from; i >= to; i--)
            {
                uint8_t hex = LITERAL_TO_HEX[(uint8_t)uuid[idx++]];
                if (hex == 0xFF)
                    return false;
                out |= static_cast<uint32_t>(hex) << (i * 4);
            }
            return true;
        };

        uint32_t idx = 0;
        if (!parseHex(m_Data[0], idx, 7, 0)) { m_Data[0] = 0; return; }
        idx++; // skip '-'
        if (!parseHex(m_Data[1], idx, 7, 4)) { m_Data[0] = m_Data[1] = 0; return; }
        idx++; // skip '-'
        if (!parseHex(m_Data[1], idx, 3, 0)) { m_Data[0] = m_Data[1] = 0; return; }
        idx++; // skip '-'
        if (!parseHex(m_Data[2], idx, 7, 4)) { m_Data[0] = m_Data[1] = m_Data[2] = 0; return; }
        idx++; // skip '-'
        if (!parseHex(m_Data[2], idx, 3, 0)) { m_Data[0] = m_Data[1] = m_Data[2] = 0; return; }
        if (!parseHex(m_Data[3], idx, 7, 0)) { m_Data[0] = m_Data[1] = m_Data[2] = m_Data[3] = 0; return; }
    }

    UUID::TextBuffer UUID::ToTextBuffer() const noexcept
    {
        TextBuffer out{};
        uint32_t idx = 0;

        for (int32_t i = 7; i >= 0; i--)
        {
            const uint32_t hex = (m_Data[0] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        out[idx++] = '-';
        for (int32_t i = 7; i >= 4; i--)
        {
            const uint32_t hex = (m_Data[1] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        out[idx++] = '-';
        for (int32_t i = 3; i >= 0; i--)
        {
            const uint32_t hex = (m_Data[1] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        out[idx++] = '-';
        for (int32_t i = 7; i >= 4; i--)
        {
            const uint32_t hex = (m_Data[2] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        out[idx++] = '-';
        for (int32_t i = 3; i >= 0; i--)
        {
            const uint32_t hex = (m_Data[2] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        for (int32_t i = 7; i >= 0; i--)
        {
            const uint32_t hex = (m_Data[3] >> (i * 4)) & 0xF;
            out[idx++] = HEX_TO_LITERAL[hex];
        }

        return out;
    }

    String UUID::ToString() const
    {
        const TextBuffer text = ToTextBuffer();
        return String(text.data(), TextLength);
    }

